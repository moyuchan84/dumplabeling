-- 0001 — 라벨 트리와 기록 라벨.
--
-- 라벨은 대분류 › 중분류 › 소분류 3단계 트리(label_defs)이고, dump 기록 한 건(scan_labels)에
-- 트리의 노드를 어느 단계에서든 하나 이상 붙인다. 정본 설명: SPEC.md 「라벨 트리」·「기록 라벨」.

CREATE TABLE label_defs (                          -- 라벨 트리 (정해진 것 + 추가된 것)
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   bigint REFERENCES label_defs(id),  -- 대분류는 NULL
    level       smallint NOT NULL,                 -- 1 대분류 · 2 중분류 · 3 소분류
    code        text NOT NULL DEFAULT '',          -- 선택: 사내 분류 코드 (예 "A-02-3")
    name        text NOT NULL,                     -- 화면에 보이는 이름
    description text NOT NULL DEFAULT '',          -- 어떤 모양인지 한 줄
    case_id     bigint,                            -- fleet 사례(acs_case) id — soft 참조, 선택
    origin      text NOT NULL DEFAULT 'seed',      -- 'seed'(처음 정해 둔 것) | 'added'(쓰다가 추가)
    retired     boolean NOT NULL DEFAULT false,    -- 더는 고르지 못하게 (지우지 않는다)
    sort_no     int,
    author      text NOT NULL DEFAULT '',          -- SSO 자리 (지금은 아무도 쓰지 않는다)
    created_at  text NOT NULL,                     -- KST ISO
    updated_at  text NOT NULL,
    CONSTRAINT label_defs_level_range CHECK (level BETWEEN 1 AND 3),
    CONSTRAINT label_defs_root_has_no_parent CHECK ((level = 1) = (parent_id IS NULL)),
    CONSTRAINT label_defs_origin CHECK (origin IN ('seed', 'added')),
    CONSTRAINT label_defs_name_not_blank CHECK (btrim(name) <> '')
);
-- 같은 부모 아래에서만 이름이 유일하다 (대소문자 · 앞뒤 공백 무시).
-- 「피크」가 「신호 이상」과 「위치 이상」 아래에 각각 있을 수 있다.
CREATE UNIQUE INDEX label_defs_sibling_name_key
    ON label_defs (COALESCE(parent_id, 0), lower(btrim(name)));
CREATE UNIQUE INDEX label_defs_code_key ON label_defs (code) WHERE code <> '';
CREATE INDEX label_defs_parent_idx ON label_defs (parent_id);

CREATE TABLE scan_labels (                         -- dump 기록 한 건 = 한 행
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servername      text NOT NULL,                 -- 장비 정체성 (fleet 의 안정 키)
    server_id       bigint NOT NULL,               -- 라벨 시점의 fleet 서버 id (링크용)
    set_name        text NOT NULL DEFAULT 'dump',
    name            text NOT NULL,                 -- 파일 이름
    source          text NOT NULL,                 -- 기록 식별 "<tdf>::<dd>"
    sig             text NOT NULL DEFAULT '',      -- 라벨 시점의 세대 (정보용, 키 아님)
    scan_enum       text NOT NULL DEFAULT '',      -- 비교 범위 (같은 스캔 종류끼리)
    meta            jsonb NOT NULL DEFAULT '{}',   -- 표시용 메타 사본 (척 · 센서 · 시각)
    label_ids       bigint[] NOT NULL,             -- label_defs.id (하나 이상, 어느 단계든)
    author          text NOT NULL DEFAULT '',      -- SSO 자리
    feature_version int  NOT NULL,
    features        jsonb NOT NULL,                -- 채널별 정규화 전 스냅샷 (shape.record_features)
    created_at      text NOT NULL,
    updated_at      text NOT NULL,
    CONSTRAINT scan_labels_record_key UNIQUE (servername, set_name, name, source),
    CONSTRAINT scan_labels_not_empty CHECK (cardinality(label_ids) > 0)
);
CREATE INDEX scan_labels_label_ids_idx ON scan_labels USING gin (label_ids);
