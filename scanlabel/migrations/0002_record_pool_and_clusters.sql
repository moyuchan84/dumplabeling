-- 0002 — 기록 풀(라벨 여부와 무관하게 본 기록)과 묶음(클러스터) 결과.
--
-- 묶음은 라벨이 **없는** 기록까지 모양으로 무리 짓는 일이라, 라벨된 기록만 담는 scan_labels 로는
-- 할 수 없다. scan_records 는 scanlabel 이 본 dump 기록마다 특징 스냅샷 한 벌을 둔다(SL-POOL).
-- 정본 설명: SPEC.md 「기록 풀」·「묶음」.

-- 풀이 바뀐 순서. 기록의 세대나 특징 판이 바뀔 때만 새 번호를 받는다 — 같은 파일을 다시 열어도
-- 그대로다. 묶음 결과가 낡았는지(cluster_runs.pool_seq 보다 큰 것이 있나)를 이것으로 판단한다.
CREATE SEQUENCE scan_records_seq;

CREATE TABLE scan_records (                        -- 본 기록 한 건 = 한 행 (라벨과 무관)
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servername      text NOT NULL,                 -- 장비 정체성 (fleet 의 안정 키)
    server_id       bigint NOT NULL,               -- 본 시점의 fleet 서버 id (링크용)
    set_name        text NOT NULL DEFAULT 'dump',
    name            text NOT NULL,                 -- 파일 이름
    source          text NOT NULL,                 -- 기록 식별 "<tdf>::<dd>"
    sig             text NOT NULL DEFAULT '',      -- 마지막으로 본 세대
    scan_enum       text NOT NULL DEFAULT '',      -- 묶음 범위 (같은 스캔 종류끼리)
    meta            jsonb NOT NULL DEFAULT '{}',   -- 표시용 메타 사본
    feature_version int  NOT NULL,
    features        jsonb NOT NULL,                -- shape.record_features — scan_labels 와 같은 모양
    seen_at         text NOT NULL,                 -- 처음 본 때 (KST ISO)
    updated_at      text NOT NULL,                 -- 마지막으로 특징을 쓴 때
    seq             bigint NOT NULL DEFAULT nextval('scan_records_seq'),
    CONSTRAINT scan_records_record_key UNIQUE (servername, set_name, name, source)
);
CREATE INDEX scan_records_scan_idx ON scan_records (set_name, scan_enum, updated_at);

-- 이미 라벨된 기록은 풀에도 있어야 한다 — 같은 스냅샷을 옮겨 둔다.
INSERT INTO scan_records (servername, server_id, set_name, name, source, sig, scan_enum, meta,
                          feature_version, features, seen_at, updated_at)
SELECT servername, server_id, set_name, name, source, sig, scan_enum, meta,
       feature_version, features, created_at, updated_at
FROM scan_labels;

CREATE TABLE index_cursors (                       -- jobs index 가 fleet /generations 를 어디까지 읽었나
    set_name   text PRIMARY KEY,
    after_id   bigint NOT NULL,                    -- fleet 세대 id (도착 순서 커서)
    updated_at text NOT NULL
);

CREATE TABLE cluster_runs (                        -- 묶음 계산 한 번 (set 마다 최신 것만 남긴다)
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_name        text NOT NULL,
    threshold       real NOT NULL,                 -- 그때의 shape.CLUSTER_MIN
    min_size        int  NOT NULL,                 -- 그때의 shape.CLUSTER_MIN_SIZE
    feature_version int  NOT NULL,
    n_records       int  NOT NULL,                 -- 묶어 본 기록 수
    n_clusters      int  NOT NULL,
    n_unclustered   int  NOT NULL,
    truncated       int  NOT NULL DEFAULT 0,       -- 상한(CLUSTER_MAX_N)에 걸려 빠진 기록 수
    pool_seq        bigint NOT NULL,               -- 묶을 때 풀의 최대 seq — 이보다 큰 seq 가 있으면 낡았다
    created_at      text NOT NULL
);

CREATE TABLE cluster_members (                     -- 묶음에 든 기록 (묶이지 않은 것은 행이 없다)
    run_id         bigint NOT NULL REFERENCES cluster_runs(id) ON DELETE CASCADE,
    cluster_no     int    NOT NULL,                -- 1부터, 큰 묶음 먼저
    record_id      bigint NOT NULL REFERENCES scan_records(id) ON DELETE CASCADE,
    scan_enum      text   NOT NULL,
    score          real   NOT NULL,                -- 대표 기록과의 유사도 (대표 자신은 1)
    representative boolean NOT NULL,
    PRIMARY KEY (run_id, record_id)
);
CREATE INDEX cluster_members_cluster_idx ON cluster_members (run_id, cluster_no);
